CREATE TABLE students (
    student_id   NUMBER GENERATED BY DEFAULT AS IDENTITY,
    first_name   VARCHAR2(50) NOT NULL,
    last_name    VARCHAR2(50) NOT NULL,
    email        VARCHAR2(100) NOT NULL,
    date_of_birth DATE,
    enrollment_date DATE DEFAULT SYSDATE NOT NULL,

    CONSTRAINT pk_students PRIMARY KEY (student_id),
    CONSTRAINT uq_students_email UNIQUE (email)
);

CREATE TABLE courses (
    course_id    NUMBER GENERATED BY DEFAULT AS IDENTITY,
    course_code  VARCHAR2(20) NOT NULL,
    course_name  VARCHAR2(100) NOT NULL,
    credits      NUMBER(2) NOT NULL,

    CONSTRAINT pk_courses PRIMARY KEY (course_id),
    CONSTRAINT uq_courses_code UNIQUE (course_code),
    CONSTRAINT chk_courses_credits CHECK (credits BETWEEN 1 AND 6)
);

CREATE TABLE enrollments (
    enrollment_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    student_id    NUMBER NOT NULL,
    course_id     NUMBER NOT NULL,
    enrollment_date DATE DEFAULT SYSDATE NOT NULL,
    grade         NUMBER(5,2),

    CONSTRAINT pk_enrollments PRIMARY KEY (enrollment_id),
    CONSTRAINT fk_enroll_student FOREIGN KEY (student_id)
        REFERENCES students(student_id),
    CONSTRAINT fk_enroll_course FOREIGN KEY (course_id)
        REFERENCES courses(course_id),
    CONSTRAINT uq_student_course UNIQUE (student_id, course_id),
    CONSTRAINT chk_enrollment_grade CHECK (grade BETWEEN 0 AND 100)
);

SELECT table_name
FROM user_tables
WHERE table_name IN ('STUDENTS', 'COURSES', 'ENROLLMENTS')
ORDER BY table_name;
